'use strict';

/*
 * Build the Phase 6.5 test harness workflow JSON.
 *
 * Output: <repo>/Response-Interpretation V1 — Test Harness.json
 *
 * The harness is the Webhook payload-injection surface for the live runner
 * (Mechanism B). Nodes 3-6 are spliced from the frozen
 * `Response-Interpretation V1.json` with EXACTLY two modular allowances on the
 * frozen Read Response Log node (both defined by the harness contract): a
 * reference-only credential block (the running n8n needs the pinned sheet's
 * credential identity to authenticate — id + name carry no secret material)
 * and alwaysOutputData=true, the empty-read continuation flag that keeps the
 * frozen chain running when the live sheet has no data rows. Structural
 * additions: the Webhook entry and the Code bridge named "Manual Trigger".
 *
 * Determinism: re-running this script reproduces byte-identical output. The
 * script asserts the harness contract before writing and refuses to emit a
 * workflow that violates it. The shipped/production artifact is never touched.
 */

const fs = require('node:fs');
const crypto = require('node:crypto');

const H = require('../src/response-interpretation-test-harness-contract');

function buildHarnessJson() {
  const frozen = H.loadFrozenWorkflow();
  const frozenByName = new Map(frozen.nodes.map((n) => [n.name, n]));
  const splice = (name) => JSON.parse(JSON.stringify(frozenByName.get(name)));

  const webhookNode = {
    parameters: {
      path: H.HARNESS_WEBHOOK_PATH,
      httpMethod: 'POST',
      responseMode: 'lastNode',
      options: {},
    },
    id: H.HARNESS_WEBHOOK_NODE_ID,
    name: 'Webhook',
    type: 'n8n-nodes-base.webhook',
    typeVersion: 2,
    position: [0, 160],
  };

  const bridgeNode = {
    parameters: {
      jsCode: H.HARNESS_BRIDGE_JAVASCRIPT,
    },
    id: H.HARNESS_BRIDGE_NODE_ID,
    name: 'Manual Trigger',
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position: [260, 160],
  };

  const readResponseLog = splice('Read Response Log');
  readResponseLog.credentials = {
    [H.HARNESS_CREDENTIAL_TYPE]: JSON.parse(JSON.stringify(H.HARNESS_PROVIDER_CREDENTIAL)),
  };
  /* Empty-read continuation flag — the contract's single documented
   * harness-side flag allowance on a spliced node (HARNESS_CONTINUATION_FLAG_NODES). */
  readResponseLog.alwaysOutputData = true;

  const nodes = [
    webhookNode,
    bridgeNode,
    splice('Read Reconciliation Report'),
    readResponseLog,
    splice('Interpret Responses'),
    splice('Response Interpretation Complete'),
  ];

  const connections = {};
  for (let i = 0; i < H.HARNESS_NODE_NAMES.length - 1; i += 1) {
    const source = H.HARNESS_NODE_NAMES[i];
    const target = H.HARNESS_NODE_NAMES[i + 1];
    connections[source] = { main: [[{ node: target, type: 'main', index: 0 }]] };
  }

  const wf = {
    id: H.HARNESS_WORKFLOW_ID,
    name: 'Response Interpretation V1 — Test Harness (Phase 6.5)',
    active: false,
    nodes,
    connections,
    meta: {
      artifact: H.HARNESS_ARTIFACT,
      purpose: 'Phase 6.5 webhook payload-injection surface for the frozen Response Interpretation V1 chain (Mechanism B)',
      provenance: 'generated by scripts/build-response-interpretation-test-harness.js; nodes 3-6 spliced byte-identical from Response-Interpretation V1.json',
      workflowId: H.HARNESS_WORKFLOW_ID,
      webhookPath: H.HARNESS_WEBHOOK_PATH,
      credentialReference: `${H.HARNESS_CREDENTIAL_TYPE} -> id/name (no secret material)`,
      spreads: ['Response Log'],
      banned: 'provider/AI/output/scheduler nodes prohibited; single Webhook entry is the only permitted exception',
    },
  };

  H.assertHarnessContract(wf);
  return wf;
}

function writeHarness(dest) {
  const wf = buildHarnessJson();
  const json = `${JSON.stringify(wf, null, 2)}\n`;
  fs.writeFileSync(dest, json);
  return json;
}

if (require.main === module) {
  const dest = H.harnessWorkflowPath();
  const json = writeHarness(dest);
  const sha = crypto.createHash('sha256').update(json).digest('hex');
  console.log(`[build-response-interpretation-test-harness] wrote ${dest}`);
  console.log(`[build-response-interpretation-test-harness] sha256 ${sha}`);
  console.log(`[build-response-interpretation-test-harness] harness contract asserted OK (${H.HARNESS_NODE_NAMES.length} nodes)`);
}

module.exports = {
  buildHarnessJson,
  writeHarness,
};