'use client';

import { useState } from 'react';
import { Platform, AIAction, ContentFormat } from '@social-media-os/shared';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import { Label } from '@/components/ui/label';
import { Select } from '@/components/ui/select';
import { Badge } from '@/components/ui/badge';
import { Tabs, TabsList, TabsTrigger, TabsContent } from '@/components/ui/tabs';
import { AISuggestionsPanel } from '@/components/ai-suggestions-panel';
import { AnalyticsChart } from '@/components/analytics-chart';
import { Sparkles, Copy, Check, Send, Loader2, History, Star } from 'lucide-react';
import { PLATFORM_LABELS, AI_ACTION_LABELS, CONTENT_FORMAT_LABELS } from '@/lib/constants';

export default function AIStudioPage() {
  const [prompt, setPrompt] = useState('');
  const [platform, setPlatform] = useState(Platform.TWITTER);
  const [action, setAction] = useState(AIAction.GENERATE);
  const [format, setFormat] = useState(ContentFormat.SHORT_CAPTION);
  const [generated, setGenerated] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [copied, setCopied] = useState(false);

  const handleGenerate = async () => {
    if (!prompt.trim()) return;
    setIsLoading(true);
    await new Promise((r) => setTimeout(r, 1500));
    setGenerated(`[Generated ${AI_ACTION_LABELS[action]} for ${PLATFORM_LABELS[platform]}]\n\n${prompt}\n\n— Generated by AI —`);
    setIsLoading(false);
  };

  const handleCopy = () => {
    if (generated) {
      navigator.clipboard.writeText(generated);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  return (
    <div className="space-y-6">
      <div className="flex items-center gap-3">
        <Sparkles className="h-6 w-6 text-brand-terracotta" />
        <div>
          <h1 className="text-2xl font-bold">AI Content Studio</h1>
          <p className="text-sm text-muted-foreground">Generate, repurpose, and optimize content with AI</p>
        </div>
      </div>

      <div className="grid grid-cols-1 gap-6 lg:grid-cols-3">
        <div className="lg:col-span-2 space-y-6">
          <Card>
            <CardHeader>
              <CardTitle className="text-base">Create Content</CardTitle>
            </CardHeader>
            <CardContent className="space-y-4">
              <div className="grid grid-cols-3 gap-4">
                <div className="space-y-2">
                  <Label>Platform</Label>
                  <Select
                    value={platform}
                    onChange={(e) => setPlatform(e.target.value as Platform)}
                    options={Object.values(Platform).map((p) => ({ value: p, label: PLATFORM_LABELS[p] }))}
                  />
                </div>
                <div className="space-y-2">
                  <Label>Action</Label>
                  <Select
                    value={action}
                    onChange={(e) => setAction(e.target.value as AIAction)}
                    options={Object.values(AIAction).map((a) => ({ value: a, label: AI_ACTION_LABELS[a] }))}
                  />
                </div>
                <div className="space-y-2">
                  <Label>Format</Label>
                  <Select
                    value={format}
                    onChange={(e) => setFormat(e.target.value as ContentFormat)}
                    options={Object.values(ContentFormat).map((f) => ({ value: f, label: CONTENT_FORMAT_LABELS[f] }))}
                  />
                </div>
              </div>

              <div className="space-y-2">
                <Label>Prompt</Label>
                <Textarea
                  placeholder="Describe what you want to create..."
                  value={prompt}
                  onChange={(e) => setPrompt(e.target.value)}
                  rows={4}
                />
              </div>

              <div className="flex gap-2">
                <Button onClick={handleGenerate} disabled={!prompt.trim() || isLoading}>
                  {isLoading ? <Loader2 className="h-4 w-4 mr-2 animate-spin" /> : <Send className="h-4 w-4 mr-2" />}
                  Generate
                </Button>
                <Button variant="outline" disabled={!prompt.trim() || isLoading}>
                  <Star className="h-4 w-4 mr-2" />
                  Save as Template
                </Button>
              </div>
            </CardContent>
          </Card>

          {generated && (
            <Card>
              <CardHeader>
                <div className="flex items-center justify-between">
                  <CardTitle className="text-base">Generated Content</CardTitle>
                  <Button variant="outline" size="sm" onClick={handleCopy}>
                    {copied ? <Check className="h-3 w-3 mr-1" /> : <Copy className="h-3 w-3 mr-1" />}
                    {copied ? 'Copied' : 'Copy'}
                  </Button>
                </div>
              </CardHeader>
              <CardContent>
                <div className="rounded-lg bg-muted p-4 whitespace-pre-wrap text-sm">
                  {generated}
                </div>
                <div className="mt-4 flex gap-2">
                  <Button size="sm"><Send className="h-3 w-3 mr-1" /> Use in Post</Button>
                  <Button variant="outline" size="sm">Regenerate</Button>
                  <Button variant="outline" size="sm">Improve</Button>
                </div>
              </CardContent>
            </Card>
          )}

          <Tabs defaultValue="history">
            <TabsList>
              <TabsTrigger value="history">Generation History</TabsTrigger>
              <TabsTrigger value="templates">Templates</TabsTrigger>
            </TabsList>
            <TabsContent value="history">
              <Card>
                <CardContent className="pt-6">
                  <div className="space-y-3">
                    {Array.from({ length: 5 }).map((_, i) => (
                      <div key={i} className="flex items-center justify-between rounded-lg border p-3">
                        <div className="min-w-0 flex-1">
                          <p className="text-sm font-medium truncate">Generated caption for Instagram</p>
                          <p className="text-xs text-muted-foreground">2 hours ago • 150 tokens</p>
                        </div>
                        <Button variant="ghost" size="sm">Reuse</Button>
                      </div>
                    ))}
                  </div>
                </CardContent>
              </Card>
            </TabsContent>
            <TabsContent value="templates">
              <Card>
                <CardContent className="pt-6">
                  <div className="grid grid-cols-1 gap-3 md:grid-cols-2">
                    {['Product Launch', 'Weekly Tip', 'Industry News', 'Behind the Scenes'].map((t) => (
                      <div key={t} className="rounded-lg border p-4 cursor-pointer hover:bg-muted transition-colors">
                        <p className="text-sm font-medium">{t}</p>
                        <p className="text-xs text-muted-foreground mt-1">Click to use this template</p>
                      </div>
                    ))}
                  </div>
                </CardContent>
              </Card>
            </TabsContent>
          </Tabs>
        </div>

        <div className="space-y-6">
          <AISuggestionsPanel
            suggestions={[
              { id: '1', type: 'content', title: 'Weekend engagement', description: 'Your audience is 40% more active on weekends', content: 'Post on Saturday morning' },
              { id: '2', type: 'hashtag', title: 'Trending hashtags', description: '#AI #SocialMediaStrategy #ContentCreation', content: 'Add these to your post' },
              { id: '3', type: 'caption', title: 'Caption style tip', description: 'Questions get 2x more comments', content: 'End with a question' },
            ]}
          />

          <Card>
            <CardHeader>
              <CardTitle className="text-sm">Usage This Month</CardTitle>
            </CardHeader>
            <CardContent>
              <div className="space-y-3">
                <div className="flex justify-between text-sm">
                  <span className="text-muted-foreground">Tokens Used</span>
                  <span className="font-medium">12,450 / 50,000</span>
                </div>
                <div className="h-2 rounded-full bg-muted overflow-hidden">
                  <div className="h-full w-1/4 rounded-full bg-brand-terracotta" />
                </div>
                <p className="text-xs text-muted-foreground">Resets in 12 days</p>
              </div>
            </CardContent>
          </Card>
        </div>
      </div>
    </div>
  );
}
